def somar (n1, n2):
    resultado = n1 + n2
    return resultado

soma = somar (5, 3)


def subtrair (n1, n2):
    resultado = n1 - n2
    return resultado

subtrai = subtrair (10, 3)

def multiplicar (n1, n2):
    resultado = n1 * n2
    return resultado

multiplica = multiplicar (2, 5)

def dividir (n1, n2):
    resultado = n1 / n2
    return resultado

divide = dividir (20, 10)

print("soma", soma)
print("subtração", subtrai)
print("multiplicação", multiplica)
print("divisão", divide)